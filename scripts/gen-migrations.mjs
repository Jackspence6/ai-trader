#!/usr/bin/env node
// Bundle db/migrations/*.sql into a TS module the Vercel app can execute, so the
// deployed dashboard can migrate its own Neon database without anything needing
// direct DB access from a build machine. Runs in `prebuild`.

import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "..");
const src = path.join(repo, "db", "migrations");
const outFile = path.join(repo, "src", "lib", "events", "migrations.generated.ts");

import { existsSync } from "node:fs";
// A deploy may only see the app root, so db/migrations can be absent.
// The generated file is committed; skip regeneration rather than failing the build.
if (!existsSync(src)) {
  console.log(`gen-migrations: ${src} not present — using the committed generated file.`);
  process.exit(0);
}

const files = readdirSync(src).filter((f) => f.endsWith(".sql")).sort();
const entries = files.map((f) => {
  const sql = readFileSync(path.join(src, f), "utf8");
  return `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(sql)} },`;
});

mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `// GENERATED by scripts/gen-migrations.mjs from db/migrations/*.sql — do not edit.
// Regenerate with: node scripts/gen-migrations.mjs (runs automatically on build).

export interface Migration { name: string; sql: string }

export const MIGRATIONS: Migration[] = [
${entries.join("\n")}
];
`,
);
console.log(`generated ${outFile} (${files.length} migrations: ${files.join(", ")})`);
